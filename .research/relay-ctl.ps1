# relay-ctl.ps1 -- start / stop / status the plugin relay on the worker.
#
# Runs the relay as the CREDENTIAL-OWNING USER in the INTERACTIVE session, which is
# required twice over: GUI work needs an interactive session, and the model credentials
# live in that user's profile (running as SYSTEM fails both).
#
# WHY schtasks.exe AND NOT Register-ScheduledTask: in this environment the Cmdlet fails
# with a CIM type-binding error ("...PSTypeName ... MSFT_TaskAction"), and because
# $ErrorActionPreference is 'Continue' the script carries on and reports success while no
# task exists. schtasks.exe has no such coupling and its exit code is trustworthy, so
# registration is verified rather than assumed.
#
# Usage:  relay-ctl.ps1 -Action start -Token <secret>
#         relay-ctl.ps1 -Action stop
#         relay-ctl.ps1 -Action status
param(
  [Parameter(Mandatory = $true)][ValidateSet('start', 'stop', 'status')][string]$Action,
  [string]$Token = '',
  [int]$Port = 7331
)

$ErrorActionPreference = 'Continue'
$d = 'C:\dsh-remote\plugin-slave'
$log = Join-Path $d 'ctl.txt'
$TASK = 'DshRelay'
$script:failures = 0

function W($m) { $m | Tee-Object -FilePath $log -Append | Out-Null; $m }
function Bad($m) { $script:failures++; W "  !! $m" }
function Ok($m) { W "  OK $m" }

W "=== $Action at $(Get-Date -Format 'HH:mm:ss') ==="

function Remove-RelayTask {
  schtasks /delete /tn $TASK /f 2>&1 | Out-Null
  Start-Sleep -Seconds 1
}

function TaskExists { return [bool](schtasks /query /tn $TASK 2>$null) }

switch ($Action) {
  'stop' {
    Stop-ScheduledTask -TaskName $TASK -ErrorAction SilentlyContinue
    Start-Sleep -Seconds 2
    Remove-RelayTask
    Get-Process node -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
    Start-Sleep -Seconds 1
    if (Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue) { Bad "port $Port still listening" }
    else { Ok "stopped, port $Port free" }
  }

  'status' {
    W ("  task exists : " + (TaskExists))
    $l = Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue
    W ("  listening   : " + $(if ($l) { ($l | ForEach-Object { $_.LocalAddress + ':' + $_.LocalPort }) -join ',' } else { 'NO' }))
    W ("  node procs  : " + (Get-Process node -ErrorAction SilentlyContinue | Measure-Object).Count)
    W ("  selfcheck   : " + (Get-Content (Join-Path $d 'selfcheck.txt') -TotalCount 1 -ErrorAction SilentlyContinue))
    W "  --- relay.log tail ---"
    W (Get-Content (Join-Path $d 'relay.log') -Tail 8 -ErrorAction SilentlyContinue | Out-String)
  }

  'start' {
    if ([string]::IsNullOrWhiteSpace($Token)) { Bad 'start requires -Token'; break }

    $sid = (Get-Process -Id $PID).SessionId
    W "  session=$sid interactive=$([Environment]::UserInteractive) user=$env:USERNAME"
    if ($sid -eq 0) { Bad 'running in session 0: the relay would have no desktop and no credentials' }
    if (-not (Test-Path "$env:USERPROFILE\.dsh\.credentials.yaml")) { Bad "credentials missing at $env:USERPROFILE\.dsh\.credentials.yaml" }
    foreach ($f in 'agent-spec.json', 'selfcheck.ps1', 'relay.mjs') {
      if (-not (Test-Path (Join-Path $d $f))) { Bad "missing $f" }
    }
    if ($script:failures -gt 0) { W '  aborting: preconditions failed'; break }

    # Clear any previous instance so repeated starts are idempotent.
    Stop-ScheduledTask -TaskName $TASK -ErrorAction SilentlyContinue
    Start-Sleep -Seconds 2
    Remove-RelayTask
    Remove-Item (Join-Path $d 'relay.log') -Force -ErrorAction SilentlyContinue

    # Write the launch command to its own file rather than embedding it in the task.
    # Two reasons: schtasks caps the /tr value at 261 characters (an EncodedCommand blows
    # past that), and a token kept out of the task definition does not show up in
    # `schtasks /query /v`. The file holds the shared secret, so its ACL is trimmed to
    # this user only.
    $runner = Join-Path $d 'run-relay.ps1'
    $runBody = @"
# GENERATED by relay-ctl.ps1 -- do not edit by hand, it is rewritten on every start.
# Contains the relay shared secret; keep the ACL restricted to this user.
`$ErrorActionPreference = 'Continue'

# Hide this wrapper's console before doing anything else.
#
# This window is long-lived: the script waits on node, so the console would otherwise sit
# on the desktop for as long as the relay runs -- and land in every screenshot the worker
# takes. `-WindowStyle Hidden` on the launcher is not enough in practice, and hiding the
# window we actually own is deterministic regardless of how we were started.
Add-Type @'
using System;
using System.Runtime.InteropServices;
public static class RelayConsole {
  [DllImport("kernel32.dll")] public static extern IntPtr GetConsoleWindow();
  [DllImport("user32.dll")] public static extern bool ShowWindow(IntPtr hWnd, int nCmdShow);
}
'@ -ErrorAction SilentlyContinue
try {
  `$h = [RelayConsole]::GetConsoleWindow()
  if (`$h -ne [IntPtr]::Zero) { [RelayConsole]::ShowWindow(`$h, 0) | Out-Null }
} catch { }

& node "$d\relay.mjs" --port $Port --token '$Token' --cmd-file "$d\agent-spec.json" --selfcheck-script "$d\selfcheck.ps1" --screenshot-script "$d\screenshot.ps1" --verbose *> "$d\relay.log"
"@
    Set-Content -Path $runner -Value $runBody -Encoding UTF8
    # Check the file, not $LASTEXITCODE: that variable only reflects native executables,
    # so the preceding (expected-to-fail) `schtasks /delete` would poison the check.
    if (-not (Test-Path $runner)) { Bad "could not write $runner"; break }
    if ((Get-Item $runner).Length -lt 50) { Bad "$runner looks truncated ($((Get-Item $runner).Length) bytes)"; break }
    Ok "launcher written ($((Get-Item $runner).Length) bytes)"
    try {
      icacls $runner /inheritance:r /grant:r "$($env:USERNAME):(R,W)" 2>&1 | Out-Null
      Ok "launcher ACL restricted to $env:USERNAME"
    } catch {
      W "  note: could not tighten ACL on $runner ($($_.Exception.Message))"
    }

    $tr = "powershell.exe -NoProfile -ExecutionPolicy Bypass -File $runner"
    W ("  /tr length = " + $tr.Length + " (limit 261)")
    $who = "$env:COMPUTERNAME\$env:USERNAME"
    $rc = (schtasks /create /tn $TASK /tr $tr /sc onlogon /ru $who /rl highest /f 2>&1 | Out-String)
    W ("  schtasks /create rc=$LASTEXITCODE")
    if ($LASTEXITCODE -ne 0) { Bad "task creation failed: $($rc.Trim())"; break }
    if (-not (TaskExists)) { Bad 'task creation reported success but the task is absent'; break }
    Ok "task created (AtLogOn as $who)"

    if (-not (Get-NetFirewallRule -Name 'dsh-relay-7331' -ErrorAction SilentlyContinue)) {
      New-NetFirewallRule -Name 'dsh-relay-7331' -DisplayName 'DSH relay 7331' -Direction Inbound -Protocol TCP -LocalPort $Port -Action Allow -Profile Any | Out-Null
      Ok "firewall rule added"
    }

    $rr = (schtasks /run /tn $TASK 2>&1 | Out-String)
    W ("  schtasks /run rc=$LASTEXITCODE")
    if ($LASTEXITCODE -ne 0) { Bad "task start failed: $($rr.Trim())" }

    # Wait for the listener rather than trusting the scheduler.
    $up = $false
    for ($i = 0; $i -lt 20; $i++) {
      Start-Sleep -Seconds 2
      if (Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue) { $up = $true; break }
    }
    if ($up) {
      Ok "listening on 0.0.0.0:$Port"
    } else {
      Bad "not listening after 40s"
      W "  --- relay.log ---"
      W (Get-Content (Join-Path $d 'relay.log') -ErrorAction SilentlyContinue | Out-String)
      # Match the English label only. cmdlet output is localized, so matching a
      # translated string would both fail here and require a non-ASCII byte in a .ps1 --
      # which corrupts PowerShell 5.1 parsing (see the ASCII note at the top).
      $info = schtasks /query /tn $TASK /fo list /v 2>&1 | Select-String 'Last Result'
      W "  $info"
    }
  }
}

W ("RESULT: " + $(if ($script:failures -eq 0) { 'OK' } else { "$script:failures problem(s)" }))
W "DONE"
